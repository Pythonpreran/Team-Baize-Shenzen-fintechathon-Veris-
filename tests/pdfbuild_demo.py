def regenerate_all(dest) -> list[str]:
    """Regenerate every demo document except the 28-page Chubb wording (which is real)
    and the deliberately illegible scan. Idempotent."""
    from pathlib import Path

    dest = Path(dest)
    written = []
    for name, builder in BUILDERS.items():
        (dest / name).write_bytes(builder())
        written.append(name)
    return written
