"""Where the worked example's documents come from, for tests.

THE EXAMPLE BUNDLE HAS TWO PROVENANCES AND THEY ARE NOT INTERCHANGEABLE.

  Thirteen SYNTHETIC documents in `demo-documents/`. We generated them with
  `tests/pdfbuild*.py`, so they are committed, served to the browser, and uploaded
  through the ordinary multipart path.

  One REAL insurer wording. It is somebody else's published, copyrighted policy
  document. The repository has a reader's right to it, not a publisher's, so it is not
  committed: it lives in the document corpus outside git, keyed by the manifest id
  `sg-chubb-selectplus-wording`, and the server attaches it from there.

Tests that upload the example need the bytes either way, and the filename the bundle is
posted under must stay `01-policy-wording.pdf` because the intake report, the source
viewer and the demo-flow assertions all key off it. So this module resolves a demo
document name to bytes and hides which of the two places it came from — while
`present()` lets a test skip, with a reason, rather than assert nothing.
"""
from __future__ import annotations

from pathlib import Path
from typing import Iterable, Optional

from proven import corpus, pipeline
from proven.api import EXAMPLE_DIR

#: The one name that is NOT in `demo-documents/`.
WORDING = "01-policy-wording.pdf"

#: Its corpus id, for `@pytest.mark.requires_corpus(demodocs.WORDING_CORPUS_ID)`.
WORDING_CORPUS_ID = pipeline.CHUBB_ID


def path(name: str) -> Path:
    """Where the bytes for this demo document live. May not exist."""
    if name == WORDING:
        return pipeline.CHUBB_PDF
    return EXAMPLE_DIR / name


def present(name: str) -> bool:
    return path(name).is_file()


def missing(names: Iterable[str]) -> list[str]:
    return [n for n in names if not present(n)]


def read(name: str) -> bytes:
    p = path(name)
    if not p.is_file():
        if name == WORDING:
            # The typed corpus signal, so conftest turns this into a skip that names
            # the document rather than a bare FileNotFoundError on an opaque path. The
            # corpus id goes with it: conftest only converts the exception into a skip
            # when that document really is absent.
            raise corpus.CorpusMissing(
                f"demo document {name!r} is the published base wording and is not in "
                f"the corpus at {p}. Fetch it with `python scripts/fetch_corpus.py "
                f"--seed-from ../06-evidence`.", document_id=WORDING_CORPUS_ID)
        raise FileNotFoundError(
            f"demo document {name!r} is not available at {p}. Synthetic documents are "
            f"generated by tests/pdfbuild*.py.")
    return p.read_bytes()


def part(name: str, field: str = "files") -> tuple[str, tuple[str, bytes, str]]:
    """One multipart part, posted under the demo filename rather than the corpus one."""
    return (field, (name, read(name), "application/pdf"))


def parts(names: Iterable[str], field: str = "files") -> list:
    return [part(n, field) for n in names]


def skip_reason(names: Iterable[str]) -> Optional[str]:
    absent = missing(names)
    if not absent:
        return None
    return ("demo documents not available: " + ", ".join(absent)
            + ". Synthetic documents come from tests/pdfbuild*.py; the published "
              "wording comes from the corpus (scripts/fetch_corpus.py).")
