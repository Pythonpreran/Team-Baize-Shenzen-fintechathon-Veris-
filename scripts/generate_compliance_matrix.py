"""Generate docs/COMPLIANCE.md from versioned jurisdiction-pack data.

The matrix is evidence inventory, not legal advice. Candidate entries remain visible for
review but are not owner-facing product statements.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PACKS = ROOT / "src" / "proven" / "jurisdictions"
OUTPUT = ROOT / "docs" / "COMPLIANCE.md"


def _entries(value):
    if isinstance(value, dict):
        verification = value.get("verification")
        identifier = value.get("id")
        if isinstance(verification, dict) and identifier:
            yield {
                "id": str(identifier),
                "title": str(value.get("title") or value.get("statement") or identifier),
                "status": str(verification.get("status") or "CANDIDATE"),
                "source_url": str(verification.get("source_url") or ""),
                "retrieved_on": str(verification.get("retrieved_on") or ""),
            }
        for child in value.values():
            yield from _entries(child)
    elif isinstance(value, list):
        for child in value:
            yield from _entries(child)


def rows() -> list[dict]:
    output = []
    for path in sorted(PACKS.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        country = str(data.get("code") or path.stem)
        seen = set()
        for entry in _entries(data):
            if entry["id"] in seen:
                continue
            seen.add(entry["id"])
            output.append({"country": country, **entry})
    return sorted(output, key=lambda row: (row["country"], row["id"]))


def _cell(value: str) -> str:
    return value.replace("|", "/").replace("\n", " ").strip() or "—"


def render() -> str:
    lines = [
        "# Jurisdiction compliance matrix", "",
        "Generated by `scripts/generate_compliance_matrix.py` from `src/proven/jurisdictions/`.",
        "It inventories verification provenance; it is not legal advice or a statement that every candidate rule is owner-facing.",
        "", "| Country | Rule | Status | Primary source | Retrieved |", "| --- | --- | --- | --- | --- |",
    ]
    for row in rows():
        source = f"[source]({_cell(row['source_url'])})" if row["source_url"] else "—"
        lines.append(f"| {_cell(row['country'])} | `{_cell(row['id'])}` — {_cell(row['title'])} | "
                     f"{_cell(row['status'])} | {source} | {_cell(row['retrieved_on'])} |")
    lines.extend([
        "", "## Status handling", "",
        "- `CANDIDATE`: retained for internal evidence review and never used for an owner-facing regulatory statement.",
        "- `SOURCE_QUOTED`: carries a primary-source quote, URL and retrieval date in its pack.",
        "- `HUMAN_VERIFIED`: retains the named team verification and needs human re-confirmation where listed in `07-fintechathon/human-actions.md`.",
        "",
    ])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    generated = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if args.check:
        if current != generated:
            print("docs/COMPLIANCE.md is out of date; run scripts/generate_compliance_matrix.py")
            return 1
        print("docs/COMPLIANCE.md is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
